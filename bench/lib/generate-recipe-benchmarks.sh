#!/usr/bin/env bash
# generate-recipe-benchmarks.sh — emit docs/netapp-recipe/BENCHMARKS.md from
# docs/netapp-recipe/benchmarks/*.json field-pilot records.
#
# Usage:
#   bench/lib/generate-recipe-benchmarks.sh [--out PATH]
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
BENCH_DIR="$REPO_ROOT/docs/netapp-recipe/benchmarks"
OUT="$REPO_ROOT/docs/netapp-recipe/BENCHMARKS.md"

while [ $# -gt 0 ]; do
  case "$1" in
    --out) OUT="$2"; shift 2 ;;
    -h|--help)
      echo "Usage: $0 [--out PATH]" >&2
      exit 0
      ;;
    *) echo "Unknown argument: $1" >&2; exit 2 ;;
  esac
done

REPO_ROOT="$REPO_ROOT" BENCH_DIR="$BENCH_DIR" OUT="$OUT" python3 <<'PY'
import json, glob, os
from datetime import datetime, timezone

repo = os.environ["REPO_ROOT"]
bench_dir = os.environ["BENCH_DIR"]
out_path = os.environ["OUT"]

records = []
for path in sorted(glob.glob(os.path.join(bench_dir, "*.json"))):
    if os.path.basename(path) == "schema.json":
        continue
    with open(path) as f:
        records.append(json.load(f))

def fmt_hours(h):
    if not h:
        return "—"
    note = h.get("note", "")
    lo, hi = h.get("min"), h.get("max")
    if lo is None and hi is None:
        return note or "—"
    if lo == hi:
        base = f"{lo:g} h"
    elif lo is not None and hi is not None:
        base = f"{lo:g}–{hi:g} h"
    else:
        base = f"{lo or hi:g} h"
    return f"{base} ({note})" if note else base

lines = []
lines.append("<!-- generated by bench/lib/generate-recipe-benchmarks.sh; edit JSON under benchmarks/ -->")
lines.append("")
lines.append("# NetApp GSD Recipe — benchmarks")
lines.append("")
lines.append(f"_Generated: {datetime.now(timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ')}_")
lines.append("")
lines.append("Two tiers of evidence:")
lines.append("")
lines.append("| Tier | What it measures | Status |")
lines.append("|------|------------------|--------|")
lines.append("| **Field benchmarks** | Real delivery on brownfield repos (recipe vs ad-hoc) | See table below |")
lines.append("| **Harness benchmarks** | Controlled baseline / vanilla GSD / recipe on fixed SPEC + hidden grader | Pending — see [../../PROJECT-SUMMARY.md](../../PROJECT-SUMMARY.md) |")
lines.append("")
lines.append("Field results are **directional pilots** — cite with caveats, not as org-wide SLAs.")
lines.append("Harness KPIs (lead time, reopen count, first-pass yield): [../../KPI-REPORT.md](../../KPI-REPORT.md).")
lines.append("")
lines.append("## Field benchmark summary")
lines.append("")
if not records:
    lines.append("_No field benchmarks recorded yet._")
else:
    lines.append("| ID | Feature | Target | Recipe | Ad-hoc | Speedup | Jira | Ship |")
    lines.append("|----|---------|--------|--------|--------|---------|------|------|")
    for r in records:
        arms = {a["id"]: a for a in r.get("arms", [])}
        recipe = arms.get("recipe", {})
        adhoc = arms.get("ad-hoc-baseline", arms.get("baseline", {}))
        oc = r.get("outcome", {})
        speed = "—"
        if oc.get("speedup_ratio_min") and oc.get("speedup_ratio_max"):
            speed = f"{oc['speedup_ratio_min']:.1f}–{oc['speedup_ratio_max']:.1f}×"
        jira = r.get("tracker", {})
        jira_cell = f"[{jira.get('issue_key', '—')}]({jira['url']})" if jira.get("url") else "—"
        ship = r.get("ship_artifact", {})
        if ship.get("url"):
            label = f"#{ship['number']}" if ship.get("number") else "PR"
            ship_cell = f"[{label}]({ship['url']})"
        else:
            ship_cell = "—"
        target = r.get("target_repo", {})
        target_cell = target.get("name", "—")
        lines.append(
            f"| `{r['id']}` | {r.get('feature', '—')} | {target_cell} "
            f"| {fmt_hours(recipe.get('wall_clock_hours'))} "
            f"| {fmt_hours(adhoc.get('wall_clock_hours'))} "
            f"| {speed} | {jira_cell} | {ship_cell} |"
        )
    lines.append("")

for r in records:
    lines.append(f"## Field benchmark — `{r['id']}`")
    lines.append("")
    lines.append(f"**Feature:** {r.get('feature', '—')} · **Recorded:** {r.get('recorded_at', '—')}")
    lines.append("")
    target = r.get("target_repo", {})
    if target.get("url"):
        lines.append(f"- **Target:** [{target.get('name', 'repo')}]({target['url']}) ({target.get('mode', '—')})")
    jira = r.get("tracker", {})
    if jira.get("url"):
        lines.append(f"- **Jira:** [{jira.get('issue_key')}]({jira['url']})")
    ship = r.get("ship_artifact", {})
    if ship.get("url"):
        lines.append(f"- **Shipped:** [PR #{ship.get('number', '?')}]({ship['url']})")
    if r.get("prd_source"):
        lines.append(f"- **PRD source:** `{r['prd_source']}`")
    lines.append("")
    lines.append("| Arm | Wall-clock | Notes |")
    lines.append("|-----|------------|-------|")
    for arm in r.get("arms", []):
        lines.append(f"| {arm.get('label', arm.get('id'))} | {fmt_hours(arm.get('wall_clock_hours'))} | {arm.get('description', '')} |")
    lines.append("")
    oc = r.get("outcome", {})
    if oc.get("summary"):
        lines.append(f"**Outcome:** {oc['summary']}")
        lines.append("")
    if r.get("caveats"):
        lines.append("**Caveats:**")
        for c in r["caveats"]:
            lines.append(f"- {c}")
        lines.append("")
    lines.append("**Citation:**")
    lines.append("")
    jkey = jira.get("issue_key", "—")
    prnum = ship.get("number", "—")
    lines.append(
        f"> {r.get('feature')} on {target.get('name', 'target')} ({jkey}, PR #{prnum}): "
        f"NetApp GSD recipe vs ad-hoc — field benchmark `{r['id']}`, {r.get('recorded_at', '—')}."
    )
    lines.append("")

lines.append("## Adding a field benchmark")
lines.append("")
lines.append("1. Copy [benchmarks/schema.json](benchmarks/schema.json) shape.")
lines.append("2. Add `docs/netapp-recipe/benchmarks/<id>.json`.")
lines.append("3. Run `bench/lib/generate-recipe-benchmarks.sh`.")
lines.append("4. Re-install or refresh targets so `docs/RECIPE-BENCHMARKS.md` updates.")
lines.append("")
lines.append("## Harness benchmark (formal)")
lines.append("")
lines.append("Run controlled arms per [../../RUNBOOK.md](../../RUNBOOK.md):")
lines.append("")
lines.append("```bash")
lines.append("./bench/runners/prepare-run.sh runs/baseline/run-01   # ad-hoc on SPEC")
lines.append("./bench/runners/prepare-run.sh runs/gsd/run-01        # vanilla GSD")
lines.append("./bench/runners/prepare-run.sh runs/recipe/run-01     # recipe arm")
lines.append("./bench/runners/finalize-run.sh <arm> run-01")
lines.append("python3 bench/report/aggregate.py")
lines.append("python3 bench/report/kpi.py")
lines.append("```")
lines.append("")
lines.append("## Related")
lines.append("")
lines.append("| Doc | Role |")
lines.append("|-----|------|")
lines.append("| [README.md](README.md) | Recipe overview |")
lines.append("| [PILOT-EVIDENCE.md](PILOT-EVIDENCE.md) | Redirect — use this file |")
lines.append("| [DECISIONS.md](DECISIONS.md) OD-01 | Org KPI thresholds after harness baseline |")

os.makedirs(os.path.dirname(out_path), exist_ok=True)
with open(out_path, "w") as f:
    f.write("\n".join(lines))
    f.write("\n")

print(f"generate-recipe-benchmarks: wrote {out_path} ({len(records)} record(s))")
PY

chmod +x "$REPO_ROOT/bench/lib/generate-recipe-benchmarks.sh"
